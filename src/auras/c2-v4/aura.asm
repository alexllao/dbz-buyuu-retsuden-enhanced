; C2 v4: individual Ki colors, no aura lightning for any fighter.
; Native entry0x9ECE and lifecycle110..115 retained; P1+116 is atlas dirty.
; Body/gold/white/lilac colors are selected per resident player atlas.
; 24phases x4fade x2air x4player/palette contexts =768pointers.
; Map shapes preserve approved80x128contour; dust always uses commonpalette3.
; Shared5C00/A260 native effects retain original loaders; custom draw/reload
; waits until both native scene flags E9C4(word) and E73C(byte) are zero.
; Source reserves the pointer table; build.py fills it from resources.json.
; Recoome normal uses remapped body data; mirrorP2 retains nativealt graphics.

aura_entry:
 tst.b (0xffffe874).w
 beq.w @aura_resources_ready
 tst.w (0xffffe9c4).w
 bne.w @aura_skip_busy
 tst.b (0xffffe73c).w
 bne.w @aura_skip_busy
 jsr @aura_load_graphics.l
aura_resources_ready:
 cmpi.b #0xc2,(0x110,A0)
 beq.w @aura_initialized
 move.b #0xc2,(0x110,A0)
 clr.b (0x111,A0)
 move.w (0xffffe6a8).w,(0x112,A0)
 move.w (0x24,A0),(0x114,A0)
aura_initialized:
 move.w (0x24,A0),D0
 cmp.w (0x114,A0),D0
 bcs.w @aura_hit_cancel
 move.w D0,(0x114,A0)
 move.w (0xffffe6a8).w,D2
 move.w D2,D4
 sub.w (0x112,A0),D4
 move.w D2,(0x112,A0)
 cmpi.w #0x10,D4
 bcs.w @aura_elapsed_valid
 clr.b (0x111,A0)
 moveq #0,D4
aura_elapsed_valid:
 tst.b (0xbd,A0)
 beq.w @aura_inactive
 cmpi.b #0x0f,(0x5b,A0)
 bne.w @aura_sustain
 ; Same charge bindings as original handler at 0x1A692.
 move.w (0x1a,A0),D0
 moveq #0,D1
 move.b (0xba,A0),D1
 btst.l D1,D0
 beq.w @aura_release
 move.b (0xbb,A0),D1
 btst.l D1,D0
 beq.w @aura_release
aura_sustain:
 move.b #0x80,(0x111,A0)
 moveq #0,D5
 bra.w @aura_draw
aura_inactive:
 ; Residual is only permitted during idle or native charge recovery.
 move.b (0x5b,A0),D0
 beq.w @aura_release
 cmpi.b #0x0f,D0
 bne.w @aura_cancel
aura_release:
 cmpi.b #0x80,(0x111,A0)
 bne.w @aura_countdown
 move.b #0x0c,(0x111,A0)
 moveq #0,D5
 bra.w @aura_draw
aura_countdown:
 moveq #0,D0
 move.b (0x111,A0),D0
 beq.w @aura_return
 sub.w D4,D0
 ble.w @aura_cancel
 move.b D0,(0x111,A0)
 moveq #0,D5
 cmpi.w #0x0a,D0
 bcc.w @aura_draw
 moveq #1,D5
 cmpi.w #0x07,D0
 bcc.w @aura_draw
 moveq #2,D5
 cmpi.w #0x04,D0
 bcc.w @aura_draw
 moveq #3,D5
aura_draw:
 ; Keep the entire contour on each visible frame. D5 selects temporal density:
 ; 0=always,1=3of4,2=1of2,3=1of4 native actor draw opportunities.
 ; Countdown state was already updated above; skipped frames still age normally.
 tst.w D5
 beq.w @aura_density_keep
 move.w (0xffffe6a8).w,D6
 lsr.w #0x1,D6
 andi.w #0x0003,D6
 cmpi.w #0x0001,D5
 beq.w @aura_density_three_quarters
 cmpi.w #0x0002,D5
 beq.w @aura_density_half
 tst.w D6
 bne.w @aura_return
 bra.w @aura_density_keep
aura_density_three_quarters:
 cmpi.w #0x0003,D6
 beq.w @aura_return
 bra.w @aura_density_keep
aura_density_half:
 andi.w #0x0001,D6
 bne.w @aura_return
aura_density_keep:
 ; D5 holds scale index0..3, converted to longword byte offset.
 lsl.w #0x2,D5
aura_animation:
 ; DIVU uses the full32bit dividend: clear D6 before loading16bit counter.
 moveq #0,D6
 move.w (0xffffe6a8).w,D6
 divu.w #0x0006,D6
 ; First quotient is in lowword; discard its remainder before second DIVU.
 andi.l #0x0000ffff,D6
 divu.w #0x0018,D6
 ; Second remainder becomes lowword after SWAP, yielding phase0..23.
 swap D6
 lsl.w #0x4,D6
 add.w D6,D5
 ; Native jump changes worldY without changing the depth-plane bit.
 ; Known ground is worldY0x1C0; all other heights use no-dust maps.
 cmpi.w #0x01c0,(0x10,A0)
 beq.w @aura_ground_map
 addi.w #0x0180,D5
aura_ground_map:
 moveq #0,D7
 cmpa.w #0xe886,A0
 bne.w @aura_player_ready
 move.w #0x0600,D7
aura_player_ready:
 moveq #0,D6
 move.b (0x58,A0),D6
 cmpi.w #0x02,D6
 beq.w @aura_actor_palette
 cmpi.w #0x06,D6
 beq.w @aura_actor_palette
 cmpi.w #0x08,D6
 beq.w @aura_actor_palette
 cmpi.w #0x09,D6
 beq.w @aura_actor_palette
 cmpi.w #0x0a,D6
 bne.w @aura_palette_ready
aura_actor_palette:
 addi.w #0x0300,D7
aura_palette_ready:
 add.w D7,D5
 ; Recreate native screen coordinates, including native Y bias.
 move.w (0x0a,A0),D0
 sub.w (0x16,A0),D0
 move.w (0x10,A0),D1
 sub.w (0x18,A0),D1
 addi.w #0x20,D1
 lea (@aura_map_table).l,A1
 adda.w D5,A1
 movea.l (A1),A0
 jsr 0x00001c66.l
 bra.w @aura_return
aura_hit_cancel:
 move.w D0,(0x114,A0)
aura_cancel:
 clr.b (0x111,A0)
aura_return:
 jmp 0x00009f08.l

aura_skip_busy:
 clr.b (0x111,A0)
 jmp 0x00009f08.l

; Each actor gets a resident flame atlas. All native temporary effect loaders
; retain their graphics. Dirty resources wait for both native scene flags.
aura_load_graphics:
 .hex 48e7fffe
 tst.w (0xffffe9c4).w
 bne.w @aura_loader_defer
 tst.b (0xffffe73c).w
 bne.w @aura_loader_defer
 moveq #0,D0
 move.b (0xffffe7b6).w,D0
 cmpi.w #0x0b,D0
 bcs.w @aura_loader_p1_valid
 moveq #0,D0
aura_loader_p1_valid:
 lsl.w #0x3,D0
 lea (0x00280000).l,A2
 adda.w D0,A2
 movea.l (A2)+,A0
 movea.w #0xa260,A1
 move.l A2,-(SP)
 jsr 0x000015d2.l
 movea.l (SP)+,A2
 movea.l (A2),A0
 movea.w #0xa820,A1
 jsr 0x000015d2.l
 moveq #0,D0
 move.b (0xffffe8de).w,D0
 cmpi.w #0x0b,D0
 bcs.w @aura_loader_p2_valid
 moveq #0,D0
aura_loader_p2_valid:
 cmpi.w #0x09,D0
 bne.w @aura_loader_p2_normal
 cmpi.b #0x09,(0xffffe7b6).w
 bne.w @aura_loader_p2_normal
 moveq #0x0b,D0
aura_loader_p2_normal:
 mulu.w #0x000c,D0
 lea (0x00280100).l,A2
 adda.w D0,A2
 movea.l (A2)+,A0
 movea.w #0xa960,A1
 move.l A2,-(SP)
 jsr 0x000015d2.l
 movea.l (SP)+,A2
 movea.l (A2)+,A0
 movea.w #0x5c00,A1
 move.l A2,-(SP)
 jsr 0x000015d2.l
 movea.l (SP)+,A2
 movea.l (A2),A0
 movea.w #0xae80,A1
 jsr 0x000015d2.l
 lea (0x00280300).l,A0
 movea.w #0xaec0,A1
 jsr 0x000015d2.l
 clr.b (0xffffe874).w
 bra.w @aura_loader_return
aura_loader_defer:
 move.b #0x01,(0xffffe874).w
aura_loader_return:
 .hex 4cdf7fff
 rts

; Reproduce native decompression before invalidating the shared aura atlases.
aura_native_effect_load:
 jsr 0x000015d2.l
 move.b #0x01,(0xffffe874).w
 rts

recoome_select_table:
 lea (0x00080000).l,A0
  .hex 20704000
 cmpi.w #0x0024,D4
 bne.w @recoome_table_done
 cmpa.w #0xe390,A4
 bne.w @recoome_table_normal
 cmpi.b #0x09,(0xffffe7b6).w
 beq.w @recoome_table_done
recoome_table_normal:
 lea (0x00227314).l,A0
recoome_table_done:
 rts

